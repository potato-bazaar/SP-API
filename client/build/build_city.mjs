// Builds dist/city.bin (+ header) from the Hong Kong GLB: 6 building types + hotel sign,
// welded, simplified, quantized, with per-vertex material bytes for a single texture-array material.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptSimplifier } from 'meshoptimizer';
import fs from 'node:fs';

const SRC = '/mnt/user-data/uploads/full_gameready_city_buildings_iv_hongkong__1__1.glb';
const S = 6.0;
const core = JSON.parse(fs.readFileSync('ext/core.json', 'utf8'));
const TYPES = { A: 'Cube_80', B: 'Cube.012_126', C: 'Cube.008_84', D: 'Cube.001_81', E: 'Cube.005_83', F: 'Cube.009_123', H: 'Text.011_251' };
const RATIO = +(process.env.RATIO || 0.55), ERR = +(process.env.ERR || 0.0015);

// texture layers (index in the array texture). name -> source image file (from ext/city)
export const LAYERS = [
  ['build15', 'img05.png'], ['build2', 'img17.png'], ['build3', 'img25.png'], ['build4', 'img13.png'], ['build6', 'img35.png'],
  ['roof1', 'img08.png'], ['roof2', 'img27.png'], ['roof3', 'img24.png'], ['walls', 'img11.jpg'], ['rustmetal', 'img06.jpg'],
  ['aircon', 'img00.png'], ['signsA', 'img12.png'], ['signsB', 'img16.png'], ['signsC', 'img29.png'], ['woodsign', 'img14.png'],
  ['rust', 'img26.png'], ['hotel', 'img48.png'],
  // masks (red-neon amount) for sign atlases, generated by build_tex
  ['signsA_m', null], ['signsB_m', null], ['signsC_m', null],
  // runtime-drawn layers
  ['custom', null],
];
const L = Object.fromEntries(LAYERS.map((l, i) => [l[0], i]));
const F_WINDOW = 1, F_NEON = 2, F_METAL = 4, F_SIGN = 8, F_ROOF = 16, F_CUSTOM = 32;
// material -> {layer, mask, flags, tint(0..255 for untextured), uvScale, uvOffset}
const MATS = {
  build1: { layer: L.build15 }, build5: { layer: L.build15 },
  build2: { layer: L.build2 }, build2glass: { layer: L.build2, flags: F_WINDOW },
  build3: { layer: L.build3 }, build3glass: { layer: L.build3, flags: F_WINDOW },
  build4: { layer: L.build4 }, build4glass: { layer: L.build4, flags: F_WINDOW },
  build6: { layer: L.build6 }, build6win: { layer: L.build6, flags: F_WINDOW },
  roof1: { layer: L.roof1, flags: F_ROOF }, roof2: { layer: L.roof2, flags: F_ROOF }, roof3: { layer: L.roof3, flags: F_ROOF },
  walls: { layer: L.walls }, material: { layer: L.rustmetal }, air_conditioner: { layer: L.aircon },
  billboard: { layer: L.signsA, mask: L.signsA_m, flags: F_SIGN }, billboard3: { layer: L.signsB, mask: L.signsB_m, flags: F_SIGN },
  billboard4: { layer: L.signsC, mask: L.signsC_m, flags: F_SIGN }, billboard2: { layer: L.woodsign },
  oggy: { layer: L.custom, flags: F_CUSTOM, mask: L.custom, uvScale: [0.5, 0.25], uvOffset: [0, 0.5] },
  rust: { layer: L.rust, uvScale: [3, 3], uvOffset: [0, -2] },
  hotel: { layer: L.hotel, flags: F_NEON },
  neon: { tint: 200, flags: F_NEON },
  metal_dark: { tint: 38, flags: F_METAL }, metal_aluminium: { tint: 120, flags: F_METAL }, bamboo: { tint: 96 },
  'Material.005_0': { tint: 30, flags: F_METAL },
};

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc = await io.read(SRC);
const nodes = doc.getRoot().listNodes();
await MeshoptSimplifier.ready;

function mulMat4Vec(m, x, y, z, w) { return [m[0] * x + m[4] * y + m[8] * z + m[12] * w, m[1] * x + m[5] * y + m[9] * z + m[13] * w, m[2] * x + m[6] * y + m[10] * z + m[14] * w]; }

function extract(type, nodeName) {
  const root = nodes.find(n => n.getName() === nodeName); if (!root) throw new Error('missing ' + nodeName);
  const P = [], N = [], UV = [], M = [], I = []; let base = 0; const seenMats = new Set();
  root.traverse(n => {
    const mesh = n.getMesh(); if (!mesh) return; const wm = n.getWorldMatrix();
    for (const prim of mesh.listPrimitives()) {
      const mname = prim.getMaterial()?.getName() ?? 'none'; const md = MATS[mname];
      if (!md) { if (!seenMats.has(mname)) console.log('  (skip material', mname, ')'); seenMats.add(mname); continue; }
      seenMats.add(mname);
      const pos = prim.getAttribute('POSITION'), nor = prim.getAttribute('NORMAL'), uv = prim.getAttribute('TEXCOORD_0'), idx = prim.getIndices();
      const cnt = pos.getCount(); const e = [];
      for (let i = 0; i < cnt; i++) {
        pos.getElement(i, e); const w = mulMat4Vec(wm, e[0], e[1], e[2], 1); P.push(w[0] * S, w[1] * S, w[2] * S);
        if (nor) { nor.getElement(i, e); const d = mulMat4Vec(wm, e[0], e[1], e[2], 0); const l = Math.hypot(d[0], d[1], d[2]) || 1; N.push(d[0] / l, d[1] / l, d[2] / l); } else N.push(0, 1, 0);
        if (uv) { uv.getElement(i, e); const sc = md.uvScale || [1, 1], of = md.uvOffset || [0, 0]; UV.push(e[0] * sc[0] + of[0], e[1] * sc[1] + of[1]); } else UV.push(0, 0);
        M.push(md.layer ?? 255, md.layer == null ? (md.tint ?? 128) : (md.mask ?? 255), md.flags || 0);
      }
      const ia = idx.getArray(); for (let i = 0; i < ia.length; i++) I.push(ia[i] + base); base += cnt;
    }
  });
  return { P: new Float32Array(P), N: new Float32Array(N), UV: new Float32Array(UV), M: new Uint8Array(M), I: new Uint32Array(I) };
}

function weld(g) { // exact-ish weld on quantized keys
  const n = g.P.length / 3, map = new Map(), remap = new Uint32Array(n); let u = 0; const keep = [];
  for (let i = 0; i < n; i++) {
    const k = `${Math.round(g.P[i * 3] * 2000)},${Math.round(g.P[i * 3 + 1] * 2000)},${Math.round(g.P[i * 3 + 2] * 2000)},${Math.round(g.N[i * 3] * 60)},${Math.round(g.N[i * 3 + 1] * 60)},${Math.round(g.N[i * 3 + 2] * 60)},${Math.round(g.UV[i * 2] * 4096)},${Math.round(g.UV[i * 2 + 1] * 4096)},${g.M[i * 3]},${g.M[i * 3 + 1]},${g.M[i * 3 + 2]}`;
    let j = map.get(k); if (j === undefined) { j = u++; map.set(k, j); keep.push(i); } remap[i] = j;
  }
  return compact(g, keep, g.I.map(i => remap[i]));
}
function compact(g, keep, I) {
  const P = new Float32Array(keep.length * 3), N = new Float32Array(keep.length * 3), UV = new Float32Array(keep.length * 2), M = new Uint8Array(keep.length * 3);
  keep.forEach((s, d) => { P.set(g.P.subarray(s * 3, s * 3 + 3), d * 3); N.set(g.N.subarray(s * 3, s * 3 + 3), d * 3); UV.set(g.UV.subarray(s * 2, s * 2 + 2), d * 2); M.set(g.M.subarray(s * 3, s * 3 + 3), d * 3); });
  // drop degenerate tris
  const out = []; for (let t = 0; t < I.length; t += 3) { const a = I[t], b = I[t + 1], c = I[t + 2]; if (a !== b && b !== c && a !== c) out.push(a, b, c); }
  return { P, N, UV, M, I: new Uint32Array(out) };
}
function dropUnused(g) {
  const used = new Uint8Array(g.P.length / 3); g.I.forEach(i => used[i] = 1); const keep = [], remap = new Uint32Array(used.length);
  for (let i = 0; i < used.length; i++) if (used[i]) { remap[i] = keep.length; keep.push(i); }
  return compact(g, keep, g.I.map(i => remap[i]));
}
function simplify(g, ratio, err) {
  const n = g.P.length / 3; const target = Math.floor(g.I.length * ratio / 3) * 3;
  // attributes: normal(3) + uv(2) + matId(1) to discourage cross-material collapses
  const A = new Float32Array(n * 6); for (let i = 0; i < n; i++) { A[i * 6] = g.N[i * 3]; A[i * 6 + 1] = g.N[i * 3 + 1]; A[i * 6 + 2] = g.N[i * 3 + 2]; A[i * 6 + 3] = g.UV[i * 2]; A[i * 6 + 4] = g.UV[i * 2 + 1]; A[i * 6 + 5] = g.M[i * 3] + g.M[i * 3 + 2] * 7; }
  const [idx, e] = MeshoptSimplifier.simplifyWithAttributes(g.I, g.P, 3, A, 6, [0.4, 0.4, 0.4, 1.5, 1.5, 4.0], null, target, err, []);
  return { g: dropUnused({ ...g, I: idx }), e };
}

const header = { scale: S, layers: LAYERS.map(l => l[0]), types: {}, posScale: 1 / 1000, uvScale: 1 / 2048 };
const chunks = []; let offset = 0;
for (const [type, nodeName] of Object.entries(TYPES)) {
  let g = extract(type, nodeName);
  const c = core[type];
  let cx, cz, ymin = 0;
  if (c) { cx = c.cx; cz = c.cz; }
  else { let mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9]; for (let i = 0; i < g.P.length; i += 3) for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], g.P[i + k]); mx[k] = Math.max(mx[k], g.P[i + k]); } cx = (mn[0] + mx[0]) / 2; cz = (mn[2] + mx[2]) / 2; ymin = (mn[1] + mx[1]) / 2; }
  for (let i = 0; i < g.P.length; i += 3) { g.P[i] -= cx; g.P[i + 1] -= ymin; g.P[i + 2] -= cz; }
  const t0 = g.I.length / 3; g = weld(g); const v1 = g.P.length / 3;
  let e = 0; if (type !== 'H') { const r = simplify(g, RATIO, ERR); g = r.g; e = r.e; }
  // mixed-material triangle check
  let mixed = 0; for (let t = 0; t < g.I.length; t += 3) { const a = g.I[t] * 3, b = g.I[t + 1] * 3, c2 = g.I[t + 2] * 3; if (g.M[a] !== g.M[b] || g.M[a] !== g.M[c2]) mixed++; }
  const nv = g.P.length / 3, nt = g.I.length / 3;
  let mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9], uvmax = 0;
  for (let i = 0; i < nv; i++) { for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], g.P[i * 3 + k]); mx[k] = Math.max(mx[k], g.P[i * 3 + k]); } uvmax = Math.max(uvmax, Math.abs(g.UV[i * 2]), Math.abs(g.UV[i * 2 + 1])); }
  // pack: pos int16x3 + layer u8 + mask u8 | normal int8x3 + flags u8 | uv int16x2  => 16 bytes
  const vb = new ArrayBuffer(nv * 16), dv = new DataView(vb);
  for (let i = 0; i < nv; i++) {
    const o = i * 16;
    for (let k = 0; k < 3; k++) dv.setInt16(o + k * 2, Math.max(-32767, Math.min(32767, Math.round(g.P[i * 3 + k] * 1000))), true);
    dv.setUint8(o + 6, g.M[i * 3]); dv.setUint8(o + 7, g.M[i * 3 + 1]);
    for (let k = 0; k < 3; k++) dv.setInt8(o + 8 + k, Math.round(g.N[i * 3 + k] * 127));
    dv.setUint8(o + 11, g.M[i * 3 + 2]);
    dv.setInt16(o + 12, Math.max(-32767, Math.min(32767, Math.round(g.UV[i * 2] * 2048))), true); dv.setInt16(o + 14, Math.max(-32767, Math.min(32767, Math.round(g.UV[i * 2 + 1] * 2048))), true);
  }
  const ib = nv < 65536 ? new Uint16Array(g.I) : new Uint32Array(g.I);
  const pad = (b) => { const p = (4 - (b.byteLength % 4)) % 4; return p ? Buffer.concat([Buffer.from(b.buffer ?? b, b.byteOffset ?? 0, b.byteLength), Buffer.alloc(p)]) : Buffer.from(b.buffer ?? b, b.byteOffset ?? 0, b.byteLength); };
  const vbuf = pad(new Uint8Array(vb)), ibuf = pad(ib);
  header.types[type] = { nv, nt, vOff: offset, iOff: offset + vbuf.length, i32: nv >= 65536, min: mn.map(x => +x.toFixed(3)), max: mx.map(x => +x.toFixed(3)), ...(c ? { hx: c.hx, hz: c.hz, roofY: c.base } : {}) };
  offset += vbuf.length + ibuf.length; chunks.push(vbuf, ibuf);
  console.log(`${type}: tris ${t0} -> ${nt} (weld verts ${v1} -> ${nv}) err=${e.toFixed(5)} mixed=${mixed} uvmax=${uvmax.toFixed(2)} bbox y[${mn[1].toFixed(1)},${mx[1].toFixed(1)}] x[${mn[0].toFixed(1)},${mx[0].toFixed(1)}] z[${mn[2].toFixed(1)},${mx[2].toFixed(1)}]`);
}
const hjson = Buffer.from(JSON.stringify(header)); const hpad = (4 - (hjson.length % 4)) % 4;
const head = Buffer.alloc(8); head.write('SCKT', 0); head.writeUInt32LE(hjson.length + hpad, 4);
const out = Buffer.concat([head, hjson, Buffer.alloc(hpad, 0x20), ...chunks]);
fs.writeFileSync(process.env.OUT || 'dist/city.bin', out);
console.log('wrote', process.env.OUT || 'dist/city.bin', (out.length / 1e6).toFixed(2), 'MB');
